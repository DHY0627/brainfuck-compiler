    src, dst = sys.argv[1], sys.argv[2]
    program = open(src, "rb").read()
    img = build(program)
    with open(dst, "wb") as f:
        f.write(img)
    print("mkstage0: %s (%d bytes of code) -> %s (%d bytes)"
          % (src, len(program), dst, len(img)))
    return 0


